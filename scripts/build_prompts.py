#!/usr/bin/env python3
"""Build the single-file prompt pack: prompts/<skill>.md for chat tools with no file system.

Each file = a short header + the SKILL.md body (frontmatter dropped, description kept
as a "When to use" line) + the skill's own authored references/ files inlined under
"## Reference: <file>" headings. The large shared files that scripts/build.py syncs
into every skill (listed in skill.manifest.json) are left out, except the "Manual
tally fallback" section of scoring.md for skills that list it. With --check nothing
is written; exit 1 if a prompt file is missing, differs, or has no matching skill.
"""
import argparse
import json
import re
import sys
from pathlib import Path

from validate_skills import FrontmatterError, parse_frontmatter, split_skill

DEFAULT_ROOT = Path(__file__).resolve().parent.parent
MAX_LINES = 1500
MANIFEST = "skill.manifest.json"
# synced shared file -> section heading to inline anyway (for skills that list the file)
SHARED_SECTIONS = {"scoring.md": "Manual tally fallback (no Python)"}
HEADER = (
    "# {name} (single-file prompt)\n"
    "\n"
    "> Single-file version of the {name} skill for chat tools without a file system. "
    "Paste into a Project / custom GPT. Scripts are not available here: follow the No-Python fallback.\n"
    ">\n"
    "> Generated by `scripts/build_prompts.py` from `skills/{name}/` in "
    "[BlockSurvey/blocksurvey-skills](https://github.com/BlockSurvey/blocksurvey-skills). "
    "Do not edit by hand. Links to `references/...` point at files in the full skill; "
    "the skill's own references are inlined at the end, the large shared ones are not.\n"
    "\n"
    "**When to use:** {description}\n"
)
HEADING_RE = re.compile(r"^(#{1,4})(\s)")


class PromptError(Exception):
    pass


def demote(lines, by=2):
    """Push markdown headings down `by` levels (outside code fences) so they nest under ## Reference."""
    out, fence = [], False
    for ln in lines:
        if ln.lstrip().startswith(("```", "~~~")):
            fence = not fence
        elif not fence:
            ln = HEADING_RE.sub(lambda m: "#" * min(6, len(m.group(1)) + by) + m.group(2), ln)
        out.append(ln)
    return out


def section(text, heading):
    """Lines of the '## heading' section of text (heading line excluded), up to the next '## '."""
    lines = text.splitlines()
    for i, ln in enumerate(lines):
        if ln.strip() == f"## {heading}":
            body = []
            for nxt in lines[i + 1:]:
                if nxt.startswith("## "):
                    break
                body.append(nxt)
            return body
    raise PromptError(f"section '## {heading}' not found")


def _strip_blank_edges(lines):
    while lines and not lines[0].strip():
        lines = lines[1:]
    while lines and not lines[-1].strip():
        lines = lines[:-1]
    return lines


def render(skill_dir):
    """Return the prompt markdown for one skill directory."""
    name = skill_dir.name
    try:
        fm_lines, body = split_skill((skill_dir / "SKILL.md").read_text(encoding="utf-8"))
        fm = parse_frontmatter(fm_lines)
    except (OSError, FrontmatterError) as exc:
        raise PromptError(f"skills/{name}/SKILL.md: {exc}")
    try:
        manifest = json.loads((skill_dir / MANIFEST).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        manifest = {}
    synced = set(manifest.get("references", []))
    parts = [HEADER.format(name=name, description=fm.get("description", "").strip())]
    parts += _strip_blank_edges(body)
    refs = skill_dir / "references"
    for ref in sorted(refs.glob("*.md")) if refs.is_dir() else []:
        if ref.name in synced:
            continue
        lines = _strip_blank_edges(ref.read_text(encoding="utf-8").splitlines())
        parts += ["", "---", "", f"## Reference: {ref.name}", ""] + demote(lines)
    for shared, heading in SHARED_SECTIONS.items():
        src = refs / shared
        if shared in synced and src.is_file():
            lines = _strip_blank_edges(section(src.read_text(encoding="utf-8"), heading))
            parts += ["", "---", "", f"## Reference: {shared} ({heading.split(' (')[0]})", ""] + demote(lines)
    return "\n".join(parts).rstrip("\n") + "\n"


def run(root, check=False, out=print):
    root = Path(root)
    skills_dir = root / "skills"
    prompts = root / "prompts"
    dirs = sorted(p for p in skills_dir.iterdir() if (p / "SKILL.md").is_file()) if skills_dir.is_dir() else []
    problems = []
    for d in dirs:
        try:
            text = render(d)
        except PromptError as exc:
            problems.append(str(exc))
            continue
        n = len(text.splitlines())
        if n > MAX_LINES:
            problems.append(f"prompts/{d.name}.md would be {n} lines (max {MAX_LINES})")
        target = prompts / f"{d.name}.md"
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == text:
            out(f"prompts/{d.name}.md: in sync ({n} lines)")
        elif check:
            problems.append(f"prompts/{d.name}.md is {'out of date' if current is not None else 'missing'} "
                            f"(run: python scripts/build_prompts.py)")
        else:
            prompts.mkdir(exist_ok=True)
            target.write_text(text, encoding="utf-8")
            out(f"prompts/{d.name}.md: written ({n} lines)")
    names = {d.name for d in dirs}
    for stray in sorted(prompts.glob("*.md")) if prompts.is_dir() else []:
        if stray.stem in names:
            continue
        if check:
            problems.append(f"prompts/{stray.name} has no matching skill (run: python scripts/build_prompts.py)")
        else:
            stray.unlink()
            out(f"prompts/{stray.name}: removed (no matching skill)")
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 on any drift")
    ap.add_argument("--root", type=Path, default=DEFAULT_ROOT, help="repository root")
    args = ap.parse_args(argv)
    problems = run(args.root, check=args.check)
    for p in problems:
        print(f"error: {p}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
